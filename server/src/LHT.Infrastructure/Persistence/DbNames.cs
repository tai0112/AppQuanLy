    public static string Table(Type clr)
        => Tables.TryGetValue(clr.Name, out var n) ? n
            : throw new InvalidOperationException($"Chưa đặt tên bảng tiếng Việt cho {clr.Name} (DbNames.Tables)");

    public static string Column(Type clr, string property)
        => ColumnOverrides.TryGetValue($"{clr.Name}.{property}", out var o) ? o
            : Columns.TryGetValue(property, out var n) ? n
            : throw new InvalidOperationException($"Chưa đặt tên cột tiếng Việt cho {clr.Name}.{property} (DbNames.Columns)");
